import test from 'node:test';
import assert from 'node:assert/strict';
import {
  computeSha256Hex,
  formatSha256SumsText,
  formatArchiveSidecarSha256Text,
  parseSha256SumsText,
  verifyFilesAgainstChecksums,
  buildChecksumManifestFilename,
  formatShortSha256,
  type ChecksumEntry,
} from './checksumUtils.ts';

test('computeSha256Hex computes standard NIST SHA-256 digests for strings, buffers, and blobs', async () => {
  const abcDigest = await computeSha256Hex('abc');
  assert.equal(
    abcDigest,
    'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad'
  );

  const bytes = new TextEncoder().encode('abc');
  assert.equal(await computeSha256Hex(bytes), abcDigest);

  const blob = new Blob([bytes], { type: 'text/plain' });
  assert.equal(await computeSha256Hex(blob), abcDigest);
});

test('formatSha256SumsText and parseSha256SumsText round-trip sha256sum -c manifests cleanly', async () => {
  const h1 = await computeSha256Hex('image-one');
  const h2 = await computeSha256Hex('image-two');
  const entries: ChecksumEntry[] = [
    { filename: 'photo1.jpg', relativePath: 'photo1.jpg', sha256: h1, bytes: 9 },
    { filename: 'photo2.png', relativePath: 'Gallery_A/photo2.png', sha256: h2, bytes: 9 },
  ];

  const text = formatSha256SumsText(entries, [
    'Generated by Ultimate Image Processor',
    'Expected images: 2',
  ]);
  assert.ok(text.includes('# Generated by Ultimate Image Processor'));
  assert.ok(text.includes(`${h1}  photo1.jpg`));
  assert.ok(text.includes(`${h2}  Gallery_A/photo2.png`));

  const parsed = parseSha256SumsText(text);
  assert.equal(parsed.length, 2);
  assert.equal(parsed[0].sha256, h1);
  assert.equal(parsed[0].relativePath, 'photo1.jpg');
  assert.equal(parsed[1].sha256, h2);
  assert.equal(parsed[1].relativePath, 'Gallery_A/photo2.png');
  assert.equal(parsed[1].filename, 'photo2.png');
});

test('formatArchiveSidecarSha256Text outputs archive checksum plus commented per-image hashes', async () => {
  const archiveHash = await computeSha256Hex('archive-bytes');
  const imgHash = await computeSha256Hex('img-1');
  const sidecar = formatArchiveSidecarSha256Text({
    archiveFilename: 'Nature.7z',
    archiveSha256: archiveHash,
    totalBytes: 12345,
    expectedImageCount: 3,
    entries: [{ filename: 'a.jpg', relativePath: 'a.jpg', sha256: imgHash, bytes: 5 }],
  });

  const parsedTopLevel = parseSha256SumsText(sidecar);
  assert.equal(parsedTopLevel.length, 1);
  assert.equal(parsedTopLevel[0].relativePath, 'Nature.7z');
  assert.equal(parsedTopLevel[0].sha256, archiveHash);
  assert.ok(sidecar.includes(`# ${imgHash}  a.jpg`));
});

test('verifyFilesAgainstChecksums identifies matched, missing, and mismatched files including folder wrapper stripping', async () => {
  const h1 = await computeSha256Hex('img-1');
  const h2 = await computeSha256Hex('img-2');
  const h3 = await computeSha256Hex('img-3');
  const corrupted = await computeSha256Hex('img-2-corrupted');

  const expected: ChecksumEntry[] = [
    { id: '1', filename: 'photo1.jpg', relativePath: 'Album_1/photo1.jpg', sha256: h1, bytes: 5 },
    { id: '2', filename: 'photo2.jpg', relativePath: 'Album_1/photo2.jpg', sha256: h2, bytes: 5 },
    { id: '3', filename: 'photo3.jpg', relativePath: 'Album_1/photo3.jpg', sha256: h3, bytes: 5 },
  ];

  const report = verifyFilesAgainstChecksums(expected, [
    // Simulate webkitdirectory adding outer selected folder name "Downloads/"
    { filename: 'photo1.jpg', relativePath: 'Downloads/Album_1/photo1.jpg', sha256: h1, sizeBytes: 5 },
    // Corrupted photo2
    { filename: 'photo2.jpg', relativePath: 'Downloads/Album_1/photo2.jpg', sha256: corrupted, sizeBytes: 15 },
    // Ignored manifest file should not be reported as extra
    { filename: 'SHA256SUMS.txt', relativePath: 'Downloads/SHA256SUMS.txt', sha256: h1, sizeBytes: 100 },
    // Unrelated local file
    { filename: 'notes.jpg', relativePath: 'Downloads/notes.jpg', sha256: h1, sizeBytes: 10 },
  ]);

  assert.equal(report.expectedCount, 3);
  assert.equal(report.verifiedCount, 1);
  assert.equal(report.missingCount, 1);
  assert.equal(report.mismatchedCount, 1);
  assert.equal(report.extraCount, 1);
  assert.equal(report.isComplete, false);
  assert.equal(report.missingEntries[0]?.filename, 'photo3.jpg');
  assert.equal(report.mismatchedEntries[0]?.expected.filename, 'photo2.jpg');

  // Complete match check
  const completeReport = verifyFilesAgainstChecksums(expected, [
    { filename: 'photo1.jpg', sha256: h1, sizeBytes: 5 },
    { filename: 'photo2.jpg', sha256: h2, sizeBytes: 5 },
    { filename: 'photo3.jpg', sha256: h3, sizeBytes: 5 },
  ]);
  assert.equal(completeReport.isComplete, true);
  assert.equal(completeReport.verifiedCount, 3);
  assert.equal(completeReport.missingCount, 0);
  assert.equal(completeReport.mismatchedCount, 0);
});

test('buildChecksumManifestFilename and formatShortSha256 format readable outputs', () => {
  assert.equal(
    buildChecksumManifestFilename('Yosemite National Park: Gallery!', 'https://example.com'),
    'Yosemite_National_Park_Gallery!_SHA256SUMS.sha256'
  );
  assert.equal(
    buildChecksumManifestFilename('', 'https://www.unsplash.com/photos'),
    'unsplash.com_SHA256SUMS.sha256'
  );
  assert.equal(
    formatShortSha256('ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad'),
    'ba7816bf…0015ad'
  );
});
